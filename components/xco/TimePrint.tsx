"use client";

// The time print's SVG pieces and the minute that drives them.
// Spec: docs/superpowers/specs/2026-11-24-time-print-design.md

import { useEffect, useState } from "react";
import { TIME_PRINT_OPACITY, minuteOf, msToNextMinute, type Minute, type TimePrint } from "@/lib/asemic/time-print";

/**
 * The current minute, ticking on each minute boundary. Null on the server and before
 * mount, so static pages hydrate cleanly. A generator calls this once and passes the
 * minute to its preview and its hidden export copies, so they always match.
 */
export function useMinute(): Minute | null {
  const [minute, setMinute] = useState<Minute | null>(null);
  useEffect(() => {
    let timer: ReturnType<typeof setTimeout> | undefined;
    const tick = () => {
      clearTimeout(timer);
      const next = minuteOf(new Date());
      // Same minute, same object: a focus within the minute regrows nothing.
      setMinute((prev) => (prev?.stamp === next.stamp ? prev : next));
      timer = setTimeout(tick, msToNextMinute(Date.now()));
    };
    tick();
    // Timers stop while a laptop sleeps and slow down in hidden tabs, so re-read the clock when the page comes back.
    const wake = () => { if (document.visibilityState !== "hidden") tick(); };
    document.addEventListener("visibilitychange", wake);
    window.addEventListener("focus", wake);
    window.addEventListener("pageshow", wake);
    return () => {
      clearTimeout(timer);
      document.removeEventListener("visibilitychange", wake);
      window.removeEventListener("focus", wake);
      window.removeEventListener("pageshow", wake);
    };
  }, []);
  return minute;
}

/**
 * The value once it has stopped changing for `ms`. The words feed the print through this, so
 * typing never waits on a regrowth: each one rewrites thousands of marks in every hidden copy.
 */
export function useSettled<T>(value: T, ms = 300): T {
  const [settled, setSettled] = useState(value);
  useEffect(() => {
    const t = setTimeout(() => setSettled(value), ms);
    return () => clearTimeout(t);
  }, [value, ms]);
  return settled;
}

/** The marks, at the back of the artwork: right after its ground. */
export function TimePrintMarks({ print }: { print: TimePrint }) {
  // The body is generated by lib/asemic from numbers and fixed colours; it carries no user text.
  return <g opacity={TIME_PRINT_OPACITY} aria-hidden="true" fill="none" strokeLinecap="butt" dangerouslySetInnerHTML={{ __html: print.body }} />;
}

/**
 * The stamp, as a printer's slug: reading upward, centred in a side margin, starting level with
 * the bottom padding. With `top`, it hangs from that y instead: on a gradient that is dark at the
 * top and light at the bottom, that keeps the whole slug where its type reads.
 */
export function TimePrintSlug({
  print,
  width,
  height,
  margin,
  bottom,
  size,
  side = "right",
  top,
}: {
  print: TimePrint;
  width: number;
  height: number;
  margin: number;
  bottom: number;
  size: number;
  side?: "left" | "right";
  top?: number;
}) {
  const x = (side === "right" ? width - margin / 2 : margin / 2) + size * 0.35;
  const y = top ?? height - bottom;
  return (
    <text
      transform={`translate(${x} ${y}) rotate(-90)`}
      textAnchor={top === undefined ? undefined : "end"}
      fontFamily="'Untitled Sans', system-ui, sans-serif"
      fontSize={size}
      fill={print.ink}
    >
      {print.stamp}
    </text>
  );
}
