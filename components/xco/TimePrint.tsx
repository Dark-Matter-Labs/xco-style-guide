"use client";

// The time print's SVG pieces and the minute that drives them.
// Spec: docs/superpowers/specs/2026-11-24-time-print-design.md

import { useEffect, useState } from "react";
import { TIME_PRINT_OPACITY, minuteOf, msToNextMinute, type Minute, type TimePrint } from "@/lib/asemic/time-print";

/**
 * The current minute, ticking on each minute boundary. Null on the server and before
 * mount, so static pages hydrate cleanly. A generator calls this once and passes the
 * minute to its preview and its hidden export copies, so they always match.
 */
export function useMinute(): Minute | null {
  const [minute, setMinute] = useState<Minute | null>(null);
  useEffect(() => {
    let timer: ReturnType<typeof setTimeout>;
    const tick = () => {
      setMinute(minuteOf(new Date()));
      timer = setTimeout(tick, msToNextMinute(Date.now()));
    };
    tick();
    return () => clearTimeout(timer);
  }, []);
  return minute;
}

/** The marks, at the back of the artwork: right after its ground. */
export function TimePrintMarks({ print }: { print: TimePrint }) {
  // The body is generated by lib/asemic from numbers and fixed colours; it carries no user text.
  return <g opacity={TIME_PRINT_OPACITY} aria-hidden="true" fill="none" strokeLinecap="butt" dangerouslySetInnerHTML={{ __html: print.body }} />;
}

/** The stamp, as a printer's slug: reading upward, centred in a side margin, starting level with the bottom padding. */
export function TimePrintSlug({
  print,
  width,
  height,
  margin,
  bottom,
  size,
  side = "right",
}: {
  print: TimePrint;
  width: number;
  height: number;
  margin: number;
  bottom: number;
  size: number;
  side?: "left" | "right";
}) {
  const x = (side === "right" ? width - margin / 2 : margin / 2) + size * 0.35;
  return (
    <text transform={`translate(${x} ${height - bottom}) rotate(-90)`} fontFamily="'Untitled Sans', system-ui, sans-serif" fontSize={size} fill={print.ink}>
      {print.stamp}
    </text>
  );
}
